std::string IRVisitor::newTemp() { return "%t" + std::to_string(tempIndex_++); }

std::string IRVisitor::llvmType(const std::string& type) const {
    if (type == "void") return "void";
    if (type == "float") return "float";
    return "i32";
}

void IRVisitor::emit(const std::string& line) {
    if (!terminated_) ir_ += "  " + line + "\n";
}

bool IRVisitor::declareSymbol(const ASTNode* ctx, const std::string& name, const Symbol& symbol) {
    if (scopes_.empty()) scopes_.emplace_back();
    auto& scope = scopes_.back();
    if (scope.find(name) != scope.end()) {
        addError(ctx, "redefinition of '" + name + "'.");
        return false;
    }
    scope.emplace(name, symbol);
    return true;
}

const IRVisitor::Symbol* IRVisitor::lookupSymbol(const std::string& name) const {
    for (auto it = scopes_.rbegin(); it != scopes_.rend(); ++it) {
        auto found = it->find(name);
        if (found != it->end()) return &found->second;
    }
    return nullptr;
}

std::string IRVisitor::evaluateConstant(const ASTNode* ctx, std::string* type) {
    if (!ctx) return "0";
    if (ctx->type == "constExp" || ctx->type == "exp")
        return evaluateConstant(ctx->children.empty() ? nullptr : ctx->children[0].get(), type);
    if (ctx->type == "addExp" || ctx->type == "mulExp") {
        if (ctx->children.size() == 1) return evaluateConstant(ctx->children[0].get(), type);
        if (ctx->children.size() >= 3) {
            std::string lhs = evaluateConstant(ctx->children[0].get(), type);
            std::string rhs = evaluateConstant(ctx->children[2].get(), type);
            char* endA = nullptr; char* endB = nullptr;
            long long a = std::strtoll(lhs.c_str(), &endA, 10);
            long long b = std::strtoll(rhs.c_str(), &endB, 10);
            if (endA && *endA == '\0' && endB && *endB == '\0') {
                const std::string op = ctx->children[1]->getText();
                if (op == "+") return std::to_string(a + b);
                if (op == "-") return std::to_string(a - b);
                if (op == "*") return std::to_string(a * b);
                if (op == "/" && b) return std::to_string(a / b);
                if (op == "%" && b) return std::to_string(a % b);
            }
        }
    }
    if (ctx->type == "unaryExp") {
        if (ctx->children.size() == 1) return evaluateConstant(ctx->children[0].get(), type);
        if (ctx->children.size() == 2) {
            std::string v = evaluateConstant(ctx->children[1].get(), type);
            if (ctx->children[0]->getText() == "-") return "-" + v;
            return v;
        }
    }
    if (ctx->type == "primaryExp") {
        if (ctx->hasChild("number")) return evaluateConstant(ctx->findChild("number"), type);
        if (ctx->hasChild("exp")) return evaluateConstant(ctx->findChild("exp"), type);
        if (ctx->hasChild("lVal")) {
            const Symbol* s = lookupSymbol(ctx->findChild("lVal")->getText());
            return s && s->isConstant ? s->constantValue : "0";
        }
    }
    if (ctx->type == "number" && !ctx->children.empty()) {
        const ASTNode* n = ctx->children[0].get();
        if (type) *type = n->type == "floatConst" ? "float" : "int";
        return n->getText();
    }
    return ctx->getText().empty() ? "0" : ctx->getText();
}

IRResult IRVisitor::run(const ASTNode* root) {
    IRResult res;
    errors_.clear(); scopes_.clear(); functions_.clear(); ir_.clear(); lastValue_.clear(); lastType_.clear();
    currentFunction_.clear(); currentReturnType_.clear(); declarationType_ = "int"; tempIndex_ = 0; terminated_ = false;
    if (!root) { res.errors.push_back("IRVisitor: AST root is null."); return res; }
    ir_ = "; generated by CmmCompiler\n";
    ir_ += "declare i32 @getint()\ndeclare i32 @getch()\ndeclare float @getfloat()\n";
    ir_ += "declare void @putint(i32)\ndeclare void @putch(i32)\ndeclare void @putfloat(float)\n";
    ir_ += "declare void @putstr(i8*)\n\n";
    scopes_.emplace_back();
    functions_["getint"] = {"int", {}, true};
    functions_["getch"] = {"int", {}, true};
    functions_["getfloat"] = {"float", {}, true};
    functions_["putint"] = {"void", {"int"}, true};
    functions_["putch"] = {"void", {"int"}, true};
    functions_["putfloat"] = {"void", {"float"}, true};
    functions_["putstr"] = {"void", {"string"}, true};
    for (const auto& fn : functions_)
        scopes_.back().emplace(fn.first, Symbol{"function", "@" + fn.first, "", true, true});
    visitProgram(root);
    res.errors = errors_;
    res.success = errors_.empty();
    res.irText = res.success ? ir_ : std::string();
    return res;
}

void IRVisitor::visitProgram(const ASTNode* ctx) {
    if (!ctx) { addError(ctx, "missing Program node."); return; }
    const ASTNode* unit = ctx->type == "compUnit" ? ctx : ctx->findChild("compUnit");
    if (!unit) { addError(ctx, "Program does not contain compUnit."); return; }
    visitCompUnit(unit);
}

void IRVisitor::visitCompUnit(const ASTNode* ctx) {
    if (!ctx) return;
    // Collect all signatures before emitting bodies, allowing forward calls.
    for (const auto& child : ctx->children) {
        if (!child || child->type != "funcDef") continue;
        const ASTNode* id = child->findChild("Ident");
        const ASTNode* ft = child->findChild("funcType");
        if (!id || !ft) continue;
        FunctionInfo info; info.returnType = ft->getText(); info.defined = true;
        if (const ASTNode* p = child->findChild("funcFParams"))
            for (const ASTNode* param : p->findChildren("funcFParam"))
                if (const ASTNode* bt = param->findChild("bType")) info.parameterTypes.push_back(bt->getText());
        const std::string name = id->getText();
        if (functions_.find(name) != functions_.end()) {
            addError(id, "redefinition of function '" + name + "'.");
        } else {
            functions_[name] = info;
            scopes_.front().emplace(name, Symbol{"function", "@" + name, "", true, true});
        }
    }
    for (const auto& child : ctx->children) {
        if (!child) continue;
        if (child->type == "decl") visitDecl(child.get());
        else if (child->type == "funcDef") visitFuncDef(child.get());
    }
}

void IRVisitor::visitDecl(const ASTNode* ctx) {
    if (!ctx) return;
    if (ctx->hasChild("constDecl")) visitConstDecl(ctx->findChild("constDecl"));
    else if (ctx->hasChild("varDecl")) visitVarDecl(ctx->findChild("varDecl"));
}

void IRVisitor::visitConstDecl(const ASTNode* ctx) {
    if (!ctx) return;
    if (const ASTNode* type = ctx->findChild("bType")) declarationType_ = type->getText();
    for (const ASTNode* def : ctx->findChildren("constDef")) visitConstDef(def);
}

void IRVisitor::visitVarDecl(const ASTNode* ctx) {
    if (!ctx) return;
    if (const ASTNode* type = ctx->findChild("bType")) declarationType_ = type->getText();
    for (const ASTNode* def : ctx->findChildren("varDef")) visitVarDef(def);
}

void IRVisitor::visitConstDef(const ASTNode* ctx) {
    if (!ctx || ctx->children.empty()) return;
    const std::string name = ctx->children[0]->getText();
    std::string type = declarationType_;
    const ASTNode* init = ctx->findChild("constInitVal");
    const std::string value = evaluateConstant(init, &type);
    Symbol symbol{type, "", value, true, scopes_.size() == 1};
    if (scopes_.size() == 1) {
        const std::string lt = llvmType(type);
        ir_ += "@" + name + " = constant " + lt + " " + value + "\n";
        symbol.address = "@" + name;
    }
    declareSymbol(ctx, name, symbol);
}

void IRVisitor::visitVarDef(const ASTNode* ctx) {
    if (!ctx || ctx->children.empty()) return;
    const std::string name = ctx->children[0]->getText();
    std::string type = declarationType_;
    if (scopes_.size() == 1) {
        const std::string value = ctx->hasChild("initVal") ? evaluateConstant(ctx->findChild("initVal")) : "0";
        Symbol symbol{type, "@" + name, "", false, true};
        if (declareSymbol(ctx, name, symbol)) ir_ += "@" + name + " = global " + llvmType(type) + " " + value + "\n";
        return;
    }
    const std::string addr = newTemp();
    emit(addr + " = alloca " + llvmType(type));
    Symbol symbol{type, addr, "", false, false};
    if (!declareSymbol(ctx, name, symbol)) return;
    if (ctx->hasChild("initVal")) {
        visitExp(ctx->findChild("initVal")->findChild("exp"));
        emit("store " + llvmType(type) + " " + lastValue_ + ", " + llvmType(type) + "* " + addr);
    }
}

void IRVisitor::visitFuncDef(const ASTNode* ctx) {
    if (!ctx) return;
    const ASTNode* id = ctx->findChild("Ident");
    const ASTNode* typeNode = ctx->findChild("funcType");
    const ASTNode* block = ctx->findChild("block");
    if (!id || !typeNode || !block || typeNode->children.empty()) { addError(ctx, "malformed function definition."); return; }
    currentFunction_ = id->getText();
    currentReturnType_ = typeNode->getText();
    const std::string resultType = llvmType(currentReturnType_);
    scopes_.emplace_back();
    std::vector<std::pair<std::string, std::string>> params;
    if (const ASTNode* p = ctx->findChild("funcFParams")) {
        int i = 0;
        for (const ASTNode* param : p->findChildren("funcFParam")) {
            const ASTNode* pid = param->findChild("Ident");
            const ASTNode* bt = param->findChild("bType");
            if (!pid || !bt) continue;
            params.emplace_back(llvmType(bt->getText()), "%arg" + std::to_string(i++));
        }
    }
    ir_ += "define " + resultType + " @" + currentFunction_ + "(";
    for (size_t i = 0; i < params.size(); ++i) { if (i) ir_ += ", "; ir_ += params[i].first + " " + params[i].second; }
    ir_ += ") {\nentry:\n";
    terminated_ = false;
    if (const ASTNode* p = ctx->findChild("funcFParams")) {
        size_t i = 0;
        for (const ASTNode* param : p->findChildren("funcFParam")) {
            const ASTNode* pid = param->findChild("Ident"); const ASTNode* bt = param->findChild("bType");
            if (!pid || !bt || i >= params.size()) continue;
            const std::string addr = newTemp();
            emit(addr + " = alloca " + params[i].first);
            emit("store " + params[i].first + " " + params[i].second + ", " + params[i].first + "* " + addr);
            declareSymbol(param, pid->getText(), Symbol{bt->getText(), addr, "", false, false}); ++i;
        }
    }
    visitBlock(block);
    if (!terminated_) emit(currentReturnType_ == "void" ? "ret void" : "ret " + resultType + " 0");
    ir_ += "}\n\n";
    scopes_.pop_back(); currentFunction_.clear(); terminated_ = false;
}

void IRVisitor::visitBlock(const ASTNode* ctx) {
    if (!ctx) return;
    scopes_.emplace_back();
    for (const ASTNode* item : ctx->findChildren("blockItem")) {
        if (terminated_) break;
        if (item->hasChild("decl")) visitDecl(item->findChild("decl"));
        else if (item->hasChild("stmt")) visitStmt(item->findChild("stmt"));
    }
    scopes_.pop_back();
}

void IRVisitor::visitStmt(const ASTNode* ctx) {
    if (!ctx || ctx->children.empty()) return;
    if (ctx->hasChild("if")) { visitIfStmt(ctx); return; }
    const ASTNode* first = ctx->children[0].get();
    if (first->type == "return") {
        const ASTNode* exp = ctx->findChild("exp");
        if (exp && currentReturnType_ != "void") { visitExp(exp); emit("ret " + llvmType(currentReturnType_) + " " + lastValue_); }
        else emit("ret void");
        terminated_ = true;
    } else if (first->type == "lVal" && ctx->children.size() >= 3) {
        const std::string name = first->getText(); const Symbol* symbol = lookupSymbol(name);
        if (!symbol) { addError(first, "use of undeclared variable '" + name + "'."); return; }
        if (symbol->isConstant) { addError(first, "cannot assign to constant '" + name + "'."); return; }
        visitExp(ctx->findChild("exp"));
        emit("store " + llvmType(symbol->type) + " " + lastValue_ + ", " + llvmType(symbol->type) + "* " + symbol->address);
    } else if (ctx->hasChild("block")) visitBlock(ctx->findChild("block"));
    else if (ctx->hasChild("exp")) visitExp(ctx->findChild("exp"));
}

void IRVisitor::visitExp(const ASTNode* ctx) { if (ctx && !ctx->children.empty()) visitAddExp(ctx->findChild("addExp")); }

void IRVisitor::visitAddExp(const ASTNode* ctx) {
    if (!ctx) return;
    if (ctx->children.size() == 1) { visitMulExp(ctx->children[0].get()); return; }
    visitAddExp(ctx->children[0].get()); std::string lhs = lastValue_, lhsType = lastType_;
    const std::string op = ctx->children[1]->getText(); visitMulExp(ctx->children[2].get());
    std::string rhs = lastValue_, rhsType = lastType_; std::string out = newTemp();
    const std::string target = (lhsType == "float" || rhsType == "float") ? "float" : "int";
    lhs = convertValue(lhs, lhsType, target, ctx);
    rhs = convertValue(rhs, rhsType, target, ctx);
    const std::string inst = target == "float" ? (op == "+" ? "fadd" : "fsub")
                                               : (op == "+" ? "add" : "sub");
    emit(out + " = " + inst + " " + llvmType(target) + " " + lhs + ", " + rhs);
    lastValue_ = out; lastType_ = target;
}

void IRVisitor::visitMulExp(const ASTNode* ctx) {
    if (!ctx) return;
    if (ctx->children.size() == 1) { visitUnaryExp(ctx->children[0].get()); return; }
    visitMulExp(ctx->children[0].get()); std::string lhs = lastValue_, lhsType = lastType_;
    const std::string op = ctx->children[1]->getText(); visitUnaryExp(ctx->children[2].get());
    std::string rhs = lastValue_, rhsType = lastType_; std::string out = newTemp();
    const std::string target = (lhsType == "float" || rhsType == "float") ? "float" : "int";
    lhs = convertValue(lhs, lhsType, target, ctx);
    rhs = convertValue(rhs, rhsType, target, ctx);
    std::string inst;
    if (target == "float") inst = op == "*" ? "fmul" : "fdiv";
    else inst = op == "*" ? "mul" : (op == "/" ? "sdiv" : "srem");
    emit(out + " = " + inst + " " + llvmType(target) + " " + lhs + ", " + rhs);
    lastValue_ = out; lastType_ = target;
}

void IRVisitor::visitUnaryExp(const ASTNode* ctx) {
    if (!ctx || ctx->children.empty()) return;
    if (ctx->children.size() == 1) { visitPrimaryExp(ctx->children[0].get()); return; }
    if (ctx->children[0]->type == "unaryOp") {
        const std::string op = ctx->children[0]->getText(); visitUnaryExp(ctx->children[1].get());
        if (op == "-") {
            std::string out = newTemp();
            if (lastType_ == "float") {
                emit(out + " = fsub float 0.000000e+00, " + lastValue_);
                lastValue_ = out;
                lastType_ = "float";
            } else {
                std::string asInt = convertValue(lastValue_, lastType_, "int", ctx);
                emit(out + " = sub i32 0, " + asInt);
                lastValue_ = out;
                lastType_ = "int";
            }
        } else if (op == "!") {
            std::string asBool = toBool(lastValue_, lastType_);
            std::string neg = newTemp();
            emit(neg + " = xor i1 " + asBool + ", true");
            std::string cast = newTemp();
            emit(cast + " = zext i1 " + neg + " to i32");
            lastValue_ = cast;
            lastType_ = "int";
        }
        return;
    }
    if (ctx->children[0]->type == "Ident") {
        const std::string name = ctx->children[0]->getText(); std::vector<std::pair<std::string, std::string>> args;
        if (const ASTNode* p = ctx->findChild("funcRParams")) for (const ASTNode* arg : p->findChildren("funcRParam")) {
            visitExp(arg->findChild("exp")); args.emplace_back(llvmType(lastType_), lastValue_);
        }
        auto found = functions_.find(name);
        if (found == functions_.end()) { addError(ctx, "call to undeclared function '" + name + "'."); lastValue_ = "0"; lastType_ = "int"; return; }
        const FunctionInfo& fn = found->second;
        if (args.size() != fn.parameterTypes.size()) addError(ctx, "function '" + name + "' expects " + std::to_string(fn.parameterTypes.size()) + " argument(s), got " + std::to_string(args.size()) + ".");
        const std::string resultType = llvmType(fn.returnType);
        std::string call = "call " + resultType + " @" + name + "(";
        for (size_t i = 0; i < args.size(); ++i) { if (i) call += ", "; call += args[i].first + " " + args[i].second; }
        call += ")"; lastType_ = fn.returnType;
        if (fn.returnType == "void") { emit(call); lastValue_ = "0"; }
        else { lastValue_ = newTemp(); emit(lastValue_ + " = " + call); }
    }
}

void IRVisitor::visitPrimaryExp(const ASTNode* ctx) {
    if (!ctx) return;
    if (ctx->hasChild("exp")) visitExp(ctx->findChild("exp"));
    else if (ctx->hasChild("cond")) visitCond(ctx->findChild("cond"));
    else if (ctx->hasChild("lVal")) visitLVal(ctx->findChild("lVal"));
    else if (ctx->hasChild("number")) visitNumber(ctx->findChild("number"));
}

void IRVisitor::visitLVal(const ASTNode* ctx) {
    if (!ctx) return;
    const std::string name = ctx->getText(); const Symbol* symbol = lookupSymbol(name);
    if (!symbol) { addError(ctx, "use of undeclared variable '" + name + "'."); lastValue_ = "0"; lastType_ = "int"; return; }
    lastType_ = symbol->type;
    if (symbol->isConstant) { lastValue_ = symbol->constantValue; return; }
    const std::string out = newTemp(); emit(out + " = load " + llvmType(symbol->type) + ", " + llvmType(symbol->type) + "* " + symbol->address); lastValue_ = out;
}

void IRVisitor::visitNumber(const ASTNode* ctx) {
    if (!ctx || ctx->children.empty()) return;
    const ASTNode* n = ctx->children[0].get();
    if (n->type == "floatConst") {
        // LLVM 要求浮点常量精确可表示，用 %.17g 打印 float 的精确值（如 3.1400001049041748e+00）
        const float value = std::strtof(n->getText().c_str(), nullptr);
        char buffer[64];
        std::snprintf(buffer, sizeof buffer, "%.17g", static_cast<double>(value));
        lastValue_ = buffer;
        lastType_ = "float";
        return;
    }
    lastValue_ = n->getText();
    lastType_ = "int";
}

void IRVisitor::visitConstExp(const ASTNode* ctx) {
    if (ctx) { std::string type; lastValue_ = evaluateConstant(ctx, &type); lastType_ = type.empty() ? "int" : type; }
}

