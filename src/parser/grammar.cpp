#include "slr.h"

namespace cmm::parser {

std::vector<Production> makeGrammar() {
    return {
        {"Program'", {"Program"}},
        {"Program", {"compUnit"}},
        {"compUnit", {"topItems", "EOF"}},
        {"topItems", {}},
        {"topItems", {"topItems", "decl"}},
        {"topItems", {"topItems", "funcDef"}},
        {"decl", {"constDecl"}},
        {"decl", {"varDecl"}},
        {"constDecl", {"const", "bType", "constDef", "constDefList", ";"}},
        {"constDefList", {}},
        {"constDefList", {"constDefList", ",", "constDef"}},
        {"bType", {"int"}},
        {"bType", {"float"}},
        {"constDef", {"Ident", "=", "constInitVal"}},
        {"constInitVal", {"constExp"}},
        {"varDecl", {"bType", "varDef", "varDefList", ";"}},
        {"varDefList", {}},
        {"varDefList", {"varDefList", ",", "varDef"}},
        {"varDef", {"Ident"}},
        {"varDef", {"Ident", "=", "initVal"}},
        {"initVal", {"exp"}},

        // 共用 bType 避开 int 后的归约冲突；函数归约时检查返回类型。
        {"funcDef", {"bType", "Ident", "(", "optFParams", ")", "block"}},
        {"funcDef", {"void", "Ident", "(", "optFParams", ")", "block"}},
        {"optFParams", {}},
        {"optFParams", {"funcFParams"}},
        {"funcFParams", {"funcFParam"}},
        {"funcFParams", {"funcFParams", ",", "funcFParam"}},
        {"funcFParam", {"bType", "Ident"}},
        {"block", {"{", "blockItems", "}"}},
        {"blockItems", {}},
        {"blockItems", {"blockItems", "blockItem"}},
        {"blockItem", {"decl"}},
        {"blockItem", {"stmt"}},

        {"stmt", {"lVal", "=", "exp", ";"}},
        {"stmt", {";"}},
        {"stmt", {"exp", ";"}},
        {"stmt", {"block"}},
        {"stmt", {"if", "(", "cond", ")", "stmt"}},
        {"stmt", {"if", "(", "cond", ")", "stmt", "else", "stmt"}},
        {"stmt", {"return", ";"}},
        {"stmt", {"return", "exp", ";"}},

        {"exp", {"addExp"}},
        {"cond", {"lOrExp"}},
        {"lVal", {"Ident"}},
        // 括号中的算术式和条件共用一条规则，避免在 ')' 上争用归约。
        {"primaryExp", {"(", "lOrExp", ")"}},
        {"primaryExp", {"lVal"}},
        {"primaryExp", {"number"}},
        {"number", {"IntConst"}},
        {"number", {"floatConst"}},
        {"unaryExp", {"primaryExp"}},
        {"unaryExp", {"Ident", "(", "optRParams", ")"}},
        {"unaryExp", {"unaryOp", "unaryExp"}},
        {"unaryOp", {"+"}},
        {"unaryOp", {"-"}},
        {"unaryOp", {"!"}},
        {"optRParams", {}},
        {"optRParams", {"funcRParams"}},
        {"funcRParams", {"funcRParam"}},
        {"funcRParams", {"funcRParams", ",", "funcRParam"}},
        {"funcRParam", {"exp"}},

        {"mulExp", {"unaryExp"}},
        {"mulExp", {"mulExp", "*", "unaryExp"}},
        {"mulExp", {"mulExp", "/", "unaryExp"}},
        {"mulExp", {"mulExp", "%", "unaryExp"}},
        {"addExp", {"mulExp"}},
        {"addExp", {"addExp", "+", "mulExp"}},
        {"addExp", {"addExp", "-", "mulExp"}},
        {"relExp", {"addExp"}},
        {"relExp", {"relExp", "<", "addExp"}},
        {"relExp", {"relExp", ">", "addExp"}},
        {"relExp", {"relExp", "<=", "addExp"}},
        {"relExp", {"relExp", ">=", "addExp"}},
        {"eqExp", {"relExp"}},
        {"eqExp", {"eqExp", "==", "relExp"}},
        {"eqExp", {"eqExp", "!=", "relExp"}},
        {"lAndExp", {"eqExp"}},
        {"lAndExp", {"lAndExp", "&&", "eqExp"}},
        {"lOrExp", {"lAndExp"}},
        {"lOrExp", {"lOrExp", "||", "lAndExp"}},
        {"constExp", {"addExp"}},
    };
}

}  // namespace cmm::parser
